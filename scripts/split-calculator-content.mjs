// One-off generator: splits the heavy per-calculator prose out of src/data/calculators.js
// into per-category modules (src/data/calcProse/<category>.js) so a calculator page only
// downloads its own category's content instead of all 60 calculators' prose (~512KB).
//
// It also:
//   - rewrites calculators.js to a meta-only module (fields, compute, formula, labels...),
//   - merges the calculatorContent* extra files into the prose modules (exact same merge
//     getCalculator used to do), and
//   - folds the extra files' data in, so the 7 legacy files can be deleted.
// Content is preserved byte-for-byte: it re-evaluates the merged object the same way
// getCalculator did and prints a verification summary for review before committing.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SRC = resolve(dirname(fileURLToPath(import.meta.url)), "..", "src");
const DATA = resolve(SRC, "data");

const { calculators, categories } = await import(`file:///${DATA.replaceAll("\\", "/")}/calculators.js`);
const { calculatorContent } = await import(`file:///${DATA.replaceAll("\\", "/")}/calculatorContent.js`);

const META_KEYS = new Set(["id", "slug", "category", "title", "description", "fields", "compute", "formula", "resultLabel", "unit", "lastUpdated", "relatedGuide"]);

// Exact merge that getCalculator(slug) used to perform before the split.
const buildMerged = (c) => {
  const extra = calculatorContent[c.slug] || {};
  return {
    ...c,
    ...extra,
    faqs: [...(extra.faqs || []), ...(c.faqs || [])],
    references: extra.references || c.references || [],
    relatedGuides: extra.relatedGuides || (c.relatedGuide ? [{ slug: c.relatedGuide.slug, title: c.relatedGuide.title }] : []),
    examples: extra.examples || c.examples || [],
    useCases: extra.useCases || c.useCases || []
  };
};

const jsLiteral = (value) => {
  if (typeof value === "function") return value.toString();
  return JSON.stringify(value, null, 2).replace(/\n(\s*)"/g, (m, ws) => `\n${ws}"`);
};

const prose = {};
let inlined = 0;
for (const c of calculators) {
  const merged = buildMerged(c);
  const entry = {};
  for (const [key, value] of Object.entries(merged)) {
    if (META_KEYS.has(key)) continue;
    if (value === undefined || value === null) continue;
    if (Array.isArray(value) && value.length === 0) continue;
    entry[key] = value;
  }
  prose[c.category] ??= {};
  prose[c.category][c.slug] = entry;
  if (Object.keys(entry).length > 0) inlined++;
}

const serializer = (obj, indent = "  ") => {
  const lines = [`{`];
  for (const [key, value] of Object.entries(obj)) {
    if (["faqs", "examples", "useCases", "references", "relatedGuides", "benefits", "commonMistakes", "whenToUse", "keywords", "results"].includes(key) && Array.isArray(value)) {
      lines.push(`${indent}${JSON.stringify(key)}: ${jsLiteral(value)},`);
    } else {
      lines.push(`${indent}${JSON.stringify(key)}: ${jsLiteral(value)},`);
    }
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
};

// 1. Prose modules
const proseDir = resolve(DATA, "calcProse");
mkdirSync(proseDir, { recursive: true });
const proseFiles = [];
for (const [category, entries] of Object.entries(prose)) {
  const rendered = [];
  for (const [slug, entry] of Object.entries(entries)) {
    rendered.push(`  ${JSON.stringify(slug)}: ${serializer(entry)}`);
  }
  const body = `// Auto-generated by scripts/split-calculator-content.mjs — do not edit by hand.\n// Prose + content extras for the ${category} calculators.\nexport const calcProse = {\n${rendered.join(",\n")}\n};\n`;
  const file = resolve(proseDir, `${category}.js`);
  writeFileSync(file, body);
  proseFiles.push(`${proseDir}/${category}.js`);
}

// 2. Meta-only calculators.js
const metaEntries = [];
for (const c of calculators) {
  const meta = {};
  for (const key of META_KEYS) {
    if (c[key] !== undefined && c[key] !== null) meta[key] = c[key];
  }
  metaEntries.push(`  ${serializer(meta, "    ")}`);
}

const calculatorsBody = `// Auto-generated by scripts/split-calculator-content.mjs — do not edit by hand.
// Meta-only: id, slug, category, title, description, fields, compute, formula, resultLabel,
// unit, lastUpdated, relatedGuide. The heavy prose lives in data/calcProse/<category>.js and
// is loaded only by the route variant of that category (see src/pages/CalculatorPage*).
import { categories } from "./categories.js";
export { categories };

export const calculators = [
${metaEntries.join(",\n")}
];

export const getCalculator = (slug) => calculators.find((item) => item.slug === slug);

export const getCategory = (id) => categories.find((item) => item.id === id);

export const calculatorsByCategory = (id) => calculators.filter((item) => item.category === id);
`;
writeFileSync(resolve(DATA, "calculators.js"), calculatorsBody);

// 3. Verification: the prose extracted from the merged objects must round-trip identically.
// Empty arrays / undefined / null are normalized to "absent" on both sides, because the page
// reads prose fields with `|| []`-style fallbacks and META keys belong to the meta module.
const normalize = (obj) => {
  const out = {};
  for (const [key, value] of Object.entries(obj || {})) {
    if (META_KEYS.has(key)) continue;
    if (value === undefined || value === null) continue;
    if (Array.isArray(value) && value.length === 0) continue;
    out[key] = value;
  }
  return out;
};

let mismatches = 0;
for (const c of calculators) {
  const expected = normalize(buildMerged(c));
  const actual = normalize(prose[c.category]?.[c.slug]);
  const a = JSON.stringify(expected);
  const b = JSON.stringify(actual);
  if (a !== b) {
    mismatches++;
    console.log(`MISMATCH ${c.slug}:`);
    for (let i = 0; i < Math.max(a.length, b.length); i++) {
      if (a[i] !== b[i]) { console.log(`  diff @${i}\n  expected: ${a.slice(Math.max(0, i - 80), i + 120)}\n  actual:   ${b.slice(Math.max(0, i - 80), i + 120)}`); break; }
    }
  }
}

console.log(`\n[split] ${calculators.length} calculators, prose kept for ${inlined}`);
console.log(`[split] wrote ${proseFiles.length} prose module(s) + meta-only calculators.js`);
if (mismatches === 0) console.log("[split] VERIFY OK: merged content is identical before/after the split.");
else { console.error(`[split] FAIL: ${mismatches} calculators differ — DO NOT COMMIT.`); process.exit(1); }